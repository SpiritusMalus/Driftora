/**
 * «Спросили ПРОДУКТ — нашли КЛАСС»: детектор запроса, который источник не
 * объяснил до конца.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ СЛОЙ. У цепочки уже есть гейт покрытия
 * ([queryCoverage]), но он сравнивает кандидата с тем именем, КОТОРЫМ СПРАШИВАЛИ
 * ЭТОГО провайдера. Для англоязычного источника это `name_en` от модели — а
 * перевод уже потерял всё, что не переводится: бренд. «отруби овсяные мистраль»
 * уходит в FatSecret как `oat bran`, строка `Oat Bran` покрывает его на 100%, и
 * generic-строка (246 ккал) останавливает цепочку с уверенностью 0.95 — до Open
 * Food Facts, где лежит настоящий продукт («Овсяные отруби Мистраль», 407 ккал),
 * очередь не доходит НИКОГДА. Пользователь получает чужое число как факт, а в
 * «других вариантах» — бейглы и хлеб с отрубями (отчёт владельца 2026-08-22).
 *
 * Гейт покрытия слеп к этому по построению: он проверяет перевод против ответа,
 * то есть НАШ вопрос против ответа на НАШ вопрос — это замкнутый круг. Здесь мы
 * задаём вопрос, которого не хватает: «осталось ли в том, что написал человек,
 * что-то, чего никто не объяснил?» — и меряем это ДВУМЯ способами, каждый в
 * своём языке (сравнивать кириллический запрос с английской строкой нельзя —
 * так любое блюдо вне нашей 200-строчной RU-таблицы выглядело бы неразобранным):
 *
 *  - источник спрашивали НА ЯЗЫКЕ ПОЛЬЗОВАТЕЛЯ → сравниваем токены напрямую
 *    ([unexplainedSpecifics]);
 *  - источник спрашивали ПЕРЕВОДОМ → сравнить не с чем, поэтому смотрим на сам
 *    перевод: если содержательных слов в нём стало МЕНЬШЕ, чем написал человек,
 *    модель что-то выбросила — и это «что-то» почти всегда бренд
 *    ([translationLost]).
 *
 * Ни одного списка брендов: они бесконечны и устаревают. Оба признака — про
 * структуру запроса, поэтому работают на продукте, которого мы никогда не
 * видели, что и требовалось (владелец: «я потом другой продукт вобью»).
 *
 * ЦЕНА ОШИБКИ НЕСИММЕТРИЧНА, и это осознанный выбор. Ложное срабатывание = мы
 * дошли до конца цепочки (медленнее на один запрос к OFF) и открыли пикер на
 * хорошем совпадении. Пропуск = чужое число выдано за факт. Второе хуже, поэтому
 * пороги настроены в сторону «лучше переспросить».
 */

import { CURATED_RU } from './curatedRu.js';
import { hasCyrillic, stemRu } from './ruSearch.js';
import { normalizeName } from './scoring.js';
import { SKURIKHIN_TABLE } from './skurikhinData.js';

/**
 * Служебные слова: в запросе они ничего не уточняют, а при переводе появляются
 * и исчезают свободно («каша с молоком» → `porridge with milk`), поэтому в счёт
 * содержательных слов не идут.
 */
const STOPWORDS = new Set([
  'с', 'со', 'на', 'в', 'во', 'из', 'и', 'а', 'по', 'для', 'от', 'до', 'у', 'к',
  'with', 'and', 'of', 'in', 'on', 'a', 'an', 'the', 'for', 'to',
]);

/**
 * Способ приготовления и бытовые уточнения. Они НЕ делают продукт другим
 * продуктом: «куриная грудка отварная» и строка «куриная грудка» — про одно и
 * то же, и гонять из-за такого хвоста всю цепочку (плюс ~5 с на Open Food Facts)
 * и открывать пикер на верном совпадении было бы регрессом. Список закрытый и
 * короткий: всё, чего в нём нет, считается уточнением по существу.
 */
const QUALIFIER_STEMS = new Set(
  [
    'варен', 'отварн', 'жарен', 'печен', 'запечен', 'тушен', 'копчен', 'солен',
    'маринован', 'квашен', 'сушен', 'вялен', 'свеж', 'заморожен', 'охлажден',
    // «сырой» осознанно НЕ здесь: его основа «сыр» совпала бы с сыром и сырниками.
    'готов', 'домашн', 'магазинн', 'покупн', 'обезжирен', 'нежирн',
    'жирн', 'цельн', 'постн', 'диетическ', 'больш', 'маленьк', 'средн',
    'половин', 'кусок', 'кусочек', 'порци', 'горст', 'ломтик', 'штук',
    'raw', 'cooked', 'boiled', 'fried', 'baked', 'grilled', 'roasted', 'steamed',
    'smoked', 'salted', 'fresh', 'frozen', 'chilled', 'dried', 'homemade',
    'large', 'small', 'medium', 'half', 'piece', 'slice', 'serving', 'portion',
  ].map((w) => stemRu(w)),
);

/** Слова запроса без служебных; числа сохраняем (сорт «5%» переживает перевод). */
export function contentTokens(s: string): string[] {
  return normalizeName(s)
    .split(' ')
    .filter((w) => w.length > 0 && !STOPWORDS.has(w));
}

/**
 * Основы совпадают с точностью до огрызка окончания, который не снял стеммер
 * («отруб» и «отруби»). Разница строго ≤ 2 символов — иначе «черноголовка»
 * съедалась бы словарным «черн» (от «чёрная смородина») и бренд считался бы
 * обычной едой; ровно на этом первая версия и попалась.
 */
function closeStems(a: string, b: string): boolean {
  const [short, long] = a.length <= b.length ? [a, b] : [b, a];
  return long.startsWith(short) && long.length - short.length <= 2;
}

/** Токен ничего не уточняет (способ приготовления, размер, порция). */
function isQualifier(token: string): boolean {
  // ЧИСЛА здесь не судьи: [normalizeName] растворяет «5%» и «3.2» в голые
  // целые («3 2»), по которым сорт от счёта штук не отличить — а голая цифра
  // («хлеб 7 злаков») демотировала верную строку как «уточнение по существу»
  // (аудит 2026-08-26). Настоящие сорта ловит резолвер ([gradesOf]) по СЫРОМУ
  // имени, где «%» и десятичная точка ещё живы.
  if (/^\d+$/.test(token)) return true;
  const stem = stemRu(token);
  if (QUALIFIER_STEMS.has(stem)) return true;
  for (const q of QUALIFIER_STEMS) if (closeStems(stem, q)) return true;
  return false;
}

/**
 * Слова RU-таблиц (основы) — наш словарь «обычной еды». Нужен, чтобы отличить
 * уточнение ПО СУЩЕСТВУ («мистраль») от обычного слова про еду, которого просто
 * нет в конкретной найденной строке («салат» в запросе «салат оливье»): второе
 * — нормальный синоним/родовое слово, из-за него дёргать всю цепочку не нужно.
 *
 * Строится один раз при загрузке модуля из тех же таблиц, что индексирует
 * SkurikhinProvider, поэтому пополняется вместе с ними и не требует ухода.
 */
const RU_FOOD_STEMS: ReadonlySet<string> = (() => {
  const stems = new Set<string>();
  for (const entry of [...SKURIKHIN_TABLE, ...CURATED_RU]) {
    for (const key of [entry.name, ...entry.aliases]) {
      for (const word of contentTokens(key)) {
        if (word.length >= 3) stems.add(stemRu(word));
      }
    }
  }
  return stems;
})();

/**
 * Слова торговых марок из выгрузки OFF (9 668 марок на 22.08.2026, включая те
 * 43 тысячи продуктов, у которых состава нет вовсе — имя марки там всё равно
 * записано). Это превращает эвристику «слова нет в словаре еды, значит уточнение»
 * в точное знание «это марка» для тех случаев, где марка СОВПАДАЕТ с обычным
 * словом («Красная цена», «Чудо», «Домик в деревне») и эвристика молчала бы.
 *
 * Пустой набор, пока файл не подложен: механизм работал и без него, список лишь
 * добавляет точности. Слова, которые есть в словаре еды, в набор не попадают —
 * иначе марка с названием «Молоко» сделала бы брендовым каждый запрос про молоко.
 */
let brandTokens: ReadonlySet<string> = new Set();
/** Многословные марки: первое слово → полные нормализованные фразы. */
let brandPhrases: ReadonlyMap<string, string[]> = new Map();

export function setKnownBrands(brands: Iterable<string>): void {
  const tokens = new Set<string>();
  const phrases = new Map<string, string[]>();
  for (const brand of brands) {
    const words = contentTokens(brand).filter((w) => w.length >= 3);
    if (words.length === 0) continue;
    if (words.length > 1) {
      // Марка из нескольких слов различима сама по себе («Красная цена», «Домик
      // в деревне»), поэтому берётся ЦЕЛИКОМ и словарь еды ей не помеха: чтобы
      // ошибиться, человек должен написать всю фразу подряд.
      const head = stemRu(words[0] as string);
      const phrase = words.join(' ');
      const list = phrases.get(head);
      if (list) list.push(phrase);
      else phrases.set(head, [phrase]);
      continue;
    }
    // Однословная марка принимается, только если это не обычное слово про еду:
    // марка с названием «Молоко» иначе сделала бы брендовым каждый запрос о молоке.
    const stem = stemRu(words[0] as string);
    if (!RU_FOOD_STEMS.has(stem)) tokens.add(stem);
  }
  brandTokens = tokens;
  brandPhrases = phrases;
}

/** Слова запроса, объяснимые как торговая марка (фраза целиком или одно слово). */
function brandWordsIn(query: string): Set<string> {
  const words = contentTokens(query);
  const out = new Set<string>();
  for (const [i, word] of words.entries()) {
    const stem = stemRu(word);
    if (brandTokens.has(stem)) out.add(word);
    const tail = words.slice(i).join(' ');
    for (const phrase of brandPhrases.get(stem) ?? []) {
      // Фраза должна идти в запросе подряд, начиная с этого слова.
      if (tail.startsWith(phrase)) for (const w of phrase.split(' ')) out.add(w);
    }
  }
  return out;
}

/** Слово встречается в наших RU-таблицах — значит, это обычное слово про еду. */
function isCommonFoodWord(token: string): boolean {
  const stem = stemRu(token);
  if (RU_FOOD_STEMS.has(stem)) return true;
  for (const s of RU_FOOD_STEMS) if (closeStems(stem, s)) return true;
  return false;
}

/**
 * Слова запроса, которых нет в названии найденной строки И которые уточняют
 * продукт по существу — бренд, сорт, незнакомое блюдо («мистраль»,
 * «черноголовка», «том ям»). Пусто, когда строка объясняет запрос.
 *
 * Применимо ТОЛЬКО когда источник спрашивали на языке пользователя: сравнивать
 * кириллический запрос с английским названием строки бессмысленно (для этого
 * есть [translationLost]).
 */
export function unexplainedSpecifics(query: string, candidateName: string): string[] {
  const explained = new Set(contentTokens(candidateName));
  const explainedStems = new Set([...explained].map(stemRu));
  const brandWords = brandWordsIn(query);
  return contentTokens(query).filter((token) => {
    if (explained.has(token) || explainedStems.has(stemRu(token))) return false;
    // Известная марка — уточнение по существу ВСЕГДА, даже если слово похоже на
    // обычное («Красная цена»): марку строка обязана объяснить, а не подменить.
    if (brandWords.has(token)) return true;
    if (isQualifier(token)) return false;
    return !isCommonFoodWord(token);
  });
}

/**
 * В запросе есть слово, которое ничем не объясняется как ОБЫЧНАЯ еда: не число,
 * не бытовое уточнение и не слово из наших продуктовых таблиц — либо известная
 * марка. Ровно такие слова перевод и теряет («мистраль», «черноголовка»,
 * «том ям»). Обычная еда, у которой русские два слова сжимаются в одно
 * английское, сюда не попадает — и это важно (см. [translationLost]).
 */
function hasUnknownSpecific(query: string): boolean {
  const brandWords = brandWordsIn(query);
  return contentTokens(query).some((token) => {
    if (brandWords.has(token)) return true;
    if (/^\d+([.,]\d+)?$/.test(token)) return false; // сорт/жирность переводится как есть
    if (isQualifier(token)) return false;
    return !isCommonFoodWord(token);
  });
}

/**
 * Перевод потерял слово: содержательных слов в запросе к англоязычному источнику
 * МЕНЬШЕ, чем написал человек. Именно так выглядит выброшенный бренд («отруби
 * овсяные мистраль» → `oat bran`), тогда как обычное уточнение переводится
 * слово в слово («творог 5%» → `cottage cheese 5%`).
 *
 * ОДНОГО счёта слов мало: у обычной еды русские два слова законно сжимаются в
 * одно английское («грецкий орех» → `walnuts», «морская капуста» → `seaweed`),
 * и для всего, что не поймала RU-таблица, чистый хит USDA/FatSecret демотировался
 * бы на чистой лингвистике. Поэтому счёт слов срабатывает ТОЛЬКО когда в запросе
 * есть слово, которое вообще нечем объяснить как обычную еду ([hasUnknownSpecific])
 * — бренд и есть такое слово, а «грецкий» и «морская» лежат в словаре таблиц.
 *
 * Только для кириллического запроса: где язык запроса и источника совпадает,
 * сравнивать нечего — там работает обычное покрытие.
 */
export function translationLost(userQuery: string, providerQuery: string): boolean {
  if (!hasCyrillic(userQuery)) return false; // запрос не на русском — переводить нечего
  if (hasCyrillic(providerQuery)) return false; // спрашивали тем же языком, это не перевод
  if (contentTokens(providerQuery).length >= contentTokens(userQuery).length) return false;
  return hasUnknownSpecific(userQuery);
}

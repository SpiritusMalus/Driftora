/**
 * Поштучный ввод: типовой вес ОДНОЙ штуки для еды, которую люди считают
 * штуками, а не граммами (яйца, фрукты, пельмени…). Владелец, 2026-08-22:
 * «нужно добавить возможность считать поштучно вещи типа яиц — они все
 * примерно одного размера».
 *
 * THE HONESTY RULE: это НЕ подмена числа — это удобный ввод. Вес штуки виден
 * прямо в контроле («≈ 50 г/шт»), граммы остаются источником истины и их
 * по-прежнему можно править руками; всё, что делает счётчик штук, — умножает.
 *
 * В список входит только то, у чего штука ДЕЙСТВИТЕЛЬНО стандартна (сортовые
 * яйца, магазинные фрукты, фабричные пельмени/сосиски). Сознательно НЕ входят
 * котлеты, сырники, куски хлеба и пирога, огурцы/помидоры — их «штука» гуляет
 * в разы, и уверенный ×N был бы враньём. Веса — съедобная часть (без скорлупы
 * и кожуры), потому что per-100g в базах — про съедобную часть.
 */

/** Формы продукта, в которых штука теряет смысл: сок из яблок — не яблоко. */
const EXCLUDE =
  /сок|нектар|фреш|смузи|пюре|джем|варень|повидл|компот|запеканк|пирог|шарлотк|чипс|сушен|сушён|вялен|цукат|juice|smoothie|jam|puree|dried|chips|pie\b/i;

/** Первое совпадение побеждает — частные случаи (перепелиное) выше общих. */
const RULES: readonly { re: RegExp; grams: number }[] = [
  // Яйца. Съедобная часть: С1 ≈ 55 г в скорлупе → ≈ 50 г без; перепелиное ≈ 10 г.
  { re: /перепелин|quail/i, grams: 10 },
  // «яйц» + «яиц» кроют падежи (яйцо/яйца/яиц); «яичница» (основа «яичн-»)
  // не матчится — и правильно: это блюдо с маслом, его per-100g уже не «яйцо».
  // EN: \b, чтобы не ловить eggplant.
  { re: /яйц|яиц|\beggs?\b/i, grams: 50 },
  // Фрукты — «средний» магазинный калибр, съедобная часть.
  { re: /банан|banana/i, grams: 120 },
  { re: /яблок|\bapples?\b/i, grams: 170 },
  { re: /апельсин|\boranges?\b/i, grams: 130 },
  { re: /мандарин|клементин|tangerine|mandarin|clementine/i, grams: 70 },
  { re: /киви|kiwi/i, grams: 70 },
  { re: /груш|\bpears?\b/i, grams: 150 },
  { re: /персик|нектарин|peach|nectarine/i, grams: 130 },
  { re: /абрикос|apricot/i, grams: 35 },
  { re: /слив[аыеу]|\bplums?\b/i, grams: 30 },
  // Фабричное штучное.
  { re: /пельмен|dumpling|pelmeni/i, grams: 12 },
  { re: /вареник|vareniki/i, grams: 14 },
  { re: /сосиск|сосисок|frankfurter|wiener/i, grams: 50 },
  { re: /сырок|сырк[аи]/i, grams: 45 }, // глазированный сырок
  { re: /хлебц|хлебец|crispbread/i, grams: 10 },
  { re: /зефир|marshmallow/i, grams: 33 },
];

/**
 * Вес одной штуки в граммах для названий блюда (RU + EN), или null, когда еда
 * не штучная / штука нестандартна — тогда UI счётчик просто не показывает.
 */
export function pieceGramsFor(...names: (string | undefined)[]): number | null {
  const hay = names.filter((n): n is string => typeof n === 'string' && n.length > 0).join(' ');
  if (hay.length === 0 || EXCLUDE.test(hay)) return null;
  for (const { re, grams } of RULES) if (re.test(hay)) return grams;
  return null;
}
